import { test, expect } from '@playwright/test';
import fs from 'node:fs';

const fixture = JSON.parse(fs.readFileSync(process.env.BROWSER_FIXTURE_PATH || '/tmp/brandguard-browser-fixture.json', 'utf8'));

test('real unsent note survives saving another revision and posts once to the original revision', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill(fixture.emails.creator);
  await page.getByLabel('Password', { exact: true }).fill(fixture.password);
  await page.getByLabel('Workspace ID').fill(fixture.org_id);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/$/);
  await page.goto('/review/new');
  await page.locator('#txt-title').fill('Real discussion draft verification');
  await page.locator('#txt-content-text').fill('LumaDesk offers a 14-day free trial.');
  const creation = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/content'));
  await page.locator('#btn-submit-review').click();
  const item = await (await creation).json();
  await expect(page).toHaveURL(/\/content\//);
  await expect(page.getByRole('button', { name: 'Edit draft', exact: true })).toBeEnabled({ timeout: 25000 });
  let posts = 0;
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/comments')) posts++; });
  const note = 'Review the wording on the original revision before we change it. 😀';
  const input = page.getByRole('textbox', { name: 'Add a discussion note' });
  await input.fill(note);
  await page.getByRole('button', { name: 'Edit draft', exact: true }).click();
  await page.getByLabel('Copy Text', { exact: true }).fill('LumaDesk offers a 14-day free trial. Explore your next workspace.');
  const revisionSaved = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/revisions'));
  await page.getByRole('button', { name: 'Save all & recheck', exact: true }).click();
  const updated = await (await revisionSaved).json();
  const secondRevisionId = updated.revisions.at(-1).id;
  await expect(page.getByRole('button', { name: 'Rev #2 (Current)', exact: true })).toBeVisible();
  await expect(input).toHaveValue('');
  await page.getByRole('button', { name: 'Open note on Rev #1', exact: true }).click({ timeout: 25000 });
  await expect(input).toHaveValue(note);
  expect(posts).toBe(0);
  const posted = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/comments'));
  await page.getByRole('button', { name: 'Post Comment', exact: true }).click();
  const response = await posted;
  expect(response.status()).toBe(201);
  expect((await response.json()).revision_id).toBe(item.revisions[0].id);
  await expect(input).toHaveValue('');
  await expect(input).toBeEnabled();
  await expect(page.getByRole('complementary', { name: 'Unsent discussion notes' })).toHaveCount(0);
  await page.reload();
  await page.getByRole('button', { name: 'Rev #1', exact: true }).click();
  await expect(page.locator('.comments-section').getByText(note, { exact: true })).toBeVisible();
  await expect(input).toHaveValue('');
  const currentNotes = page.waitForResponse(response => response.request().method() === 'GET' && response.url().endsWith(`/revisions/${secondRevisionId}/comments`));
  await page.getByRole('button', { name: 'Rev #2 (Current)', exact: true }).click();
  expect(await (await currentNotes).json()).toEqual([]);
  await expect(page.locator('.comments-section').getByText(note, { exact: true })).toHaveCount(0);
  expect(posts).toBe(1);
});
